/**
 * Ops alerts — the ONE way a watchdog Edge Function tells a human something is
 * wrong (#576). First user: notification-health-check; next: the stale-closeout
 * alert (#575).
 *
 * Sink: `OPS_ALERT_WEBHOOK_URL` (EF secret). Its shape is chosen by
 * `OPS_ALERT_WEBHOOK_FORMAT`:
 *   - `teams` (default) — a Microsoft Teams *Workflows* webhook ("When a Teams
 *     webhook request is received" → post card to a channel). Body is
 *     `{ type: 'message', attachments: [{ contentType: adaptive, contentUrl: null,
 *     content: <Adaptive Card> }] }`. The legacy O365 connector webhooks are
 *     retired, and Workflows URLs moved host in 2025 (logic.azure.com →
 *     *.environment.api.powerplatform.com), so the format is an explicit
 *     setting, never sniffed from the URL.
 *   - `slack` — any endpoint taking `{ text }` (the original contract).
 *
 * The sink is deliberately independent of SendGrid and Twilio: an alert about a
 * dead email/SMS channel must not ride that same channel.
 *
 * Never silent: a missing URL, an unknown format, a thrown POST or a non-2xx
 * answer each raise a PII-free Sentry warning naming the cause (`captureWarning`
 * is injected — `_shared/sentry.ts` in the EF, a spy in tests). The watchdog ran
 * for three months with no URL set and nobody could tell (#576).
 *
 * PII: callers pass counts, channels and booking refs only. As a backstop every
 * line is scrubbed of email addresses and phone numbers (a Twilio error message
 * quotes the `To` number) and capped in length. The webhook URL carries its own
 * signature, so it is NEVER logged, returned or sent to Sentry — Deno puts the
 * request URL into fetch error messages, which are stripped of URLs here.
 *
 * Mirror: this `_shared/` file is the source of truth. Its Node twin at
 * `src/lib/notifications/ops-alert.ts` is generated by `scripts/sync-mirrors.sh`
 * for Vitest (`src/__tests__/notifications/ops-alert.test.ts`). Pure — no Deno
 * globals, no remote imports; the EF reads the env and passes it in.
 */

export type OpsAlertFormat = 'teams' | 'slack'

export const DEFAULT_OPS_ALERT_FORMAT: OpsAlertFormat = 'teams'

/** Admin host the alert links point at (ops alerts are production-only). */
export const ADMIN_ORIGIN = 'https://admin.verco.au'

/** Per-request cap so a hung webhook can't hold a cron EF to the edge limit. */
export const OPS_ALERT_TIMEOUT_MS = 10_000

/** Longest line kept in an alert — a raw provider error can be a JSON essay. */
export const MAX_LINE_LENGTH = 300

/** Webhook response text kept for the caller (the test alert returns it). */
const MAX_RESPONSE_BODY_LENGTH = 500

export interface OpsAlertLink {
  label: string
  url: string
}

export interface OpsAlert {
  /** The job raising it, e.g. 'notification-health-check'. Shown in the footer. */
  source: string
  /** One-line headline. */
  title: string
  /** Body, one entry per line. An empty string is a paragraph break. */
  lines: string[]
  /** Links into admin — never to anything carrying resident details. */
  links?: OpsAlertLink[]
  /** Runbook test message — labelled so nobody mistakes it for a real alert. */
  test?: boolean
}

export interface OpsAlertConfig {
  /** `OPS_ALERT_WEBHOOK_URL`. */
  webhookUrl: string | undefined
  /** `OPS_ALERT_WEBHOOK_FORMAT` — unset means teams. */
  format: string | undefined
}

export interface OpsAlertDeps {
  /** `captureWarning` from `_shared/sentry.ts`. */
  captureWarning: (message: string, extra?: Record<string, unknown>) => void
  fetch?: typeof fetch
  /** Footer timestamp — injected so tests are deterministic. */
  now?: Date
}

export type OpsAlertResult =
  | { delivered: true; format: OpsAlertFormat; status: number; responseBody: string }
  | {
      delivered: false
      reason: 'not_configured' | 'invalid_format' | 'webhook_failed'
      /** Safe to log / return: names the missing secret or the HTTP failure, no URL. */
      error: string
      format: OpsAlertFormat | null
      status: number | null
      responseBody: string | null
    }

/**
 * `OPS_ALERT_WEBHOOK_FORMAT` → format. Unset/blank → teams; case and spaces are
 * ignored; anything else → null (the caller treats it as a config error rather
 * than guess — the runbook's test alert surfaces a typo straight away).
 */
export function parseOpsAlertFormat(raw: string | null | undefined): OpsAlertFormat | null {
  const value = (raw ?? '').trim().toLowerCase()
  if (value === '') return DEFAULT_OPS_ALERT_FORMAT
  if (value === 'teams' || value === 'slack') return value
  return null
}

const EMAIL_RE = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g
// 8–15 digits, optionally `+`-prefixed, single spaces allowed between digits:
// +61412345678, 0412 345 678, 0895551234. Deliberately NOT the Sentry
// scrubber's pattern — that one allows `-` and eats ISO dates (2026-10-20),
// which alerts print as "last success".
const PHONE_RE = /\+?\d(?: ?\d){7,14}/g
const URL_RE = /https?:\/\/[^\s)'"<>]+/g

/** Strip email addresses and phone numbers from free text. */
export function redactPii(text: string): string {
  return text.replace(EMAIL_RE, '[email]').replace(PHONE_RE, '[phone]')
}

/** Strip any URL — used on fetch errors, which quote the signed webhook URL. */
export function redactUrls(text: string): string {
  return text.replace(URL_RE, '[webhook url]')
}

function cleanLine(line: string): string {
  const scrubbed = redactPii(line)
  return scrubbed.length > MAX_LINE_LENGTH ? `${scrubbed.slice(0, MAX_LINE_LENGTH - 1)}…` : scrubbed
}

function displayTitle(alert: OpsAlert): string {
  const title = cleanLine(alert.title)
  return alert.test ? `TEST — ${title}` : title
}

/** "20/10/2026 15:15 AWST" — Perth time, DD/MM/YYYY. */
export function formatAwst(at: Date): string {
  const parts = new Intl.DateTimeFormat('en-AU', {
    timeZone: 'Australia/Perth',
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
  }).formatToParts(at)
  const get = (type: string) => parts.find((p) => p.type === type)?.value ?? ''
  return `${get('day')}/${get('month')}/${get('year')} ${get('hour')}:${get('minute')} AWST`
}

function footer(alert: OpsAlert, now: Date): string {
  return `Sent by ${alert.source} · ${formatAwst(now)}`
}

/** The alert as plain text — the Slack body, and readable in EF logs. */
export function opsAlertText(alert: OpsAlert, now: Date = new Date()): string {
  const out = [displayTitle(alert), ...alert.lines.map(cleanLine)]
  if (alert.links && alert.links.length > 0) {
    out.push('', ...alert.links.map((l) => `${cleanLine(l.label)}: ${l.url}`))
  }
  out.push('', footer(alert, now))
  return out.join('\n')
}

type AdaptiveElement = Record<string, unknown>

/** The Adaptive Card body posted to Teams. */
export function buildAdaptiveCard(alert: OpsAlert, now: Date = new Date()): Record<string, unknown> {
  const body: AdaptiveElement[] = [
    {
      type: 'TextBlock',
      text: displayTitle(alert),
      weight: 'Bolder',
      size: 'Medium',
      color: alert.test ? 'Accent' : 'Attention',
      wrap: true,
    },
  ]
  // A blank line becomes extra spacing on the next block — an empty TextBlock
  // is not valid card content.
  let gap = false
  for (const line of alert.lines) {
    if (line.trim() === '') {
      gap = true
      continue
    }
    body.push({ type: 'TextBlock', text: cleanLine(line), wrap: true, spacing: gap ? 'Medium' : 'Small' })
    gap = false
  }
  if (alert.links && alert.links.length > 0) {
    body.push({
      type: 'TextBlock',
      text: alert.links.map((l) => `[${cleanLine(l.label)}](${l.url})`).join(' · '),
      wrap: true,
      spacing: 'Medium',
    })
  }
  body.push({ type: 'TextBlock', text: footer(alert, now), isSubtle: true, size: 'Small', wrap: true, spacing: 'Medium' })
  return {
    $schema: 'http://adaptivecards.io/schemas/adaptive-card.json',
    type: 'AdaptiveCard',
    version: '1.4',
    msteams: { width: 'Full' },
    body,
  }
}

/** The exact JSON body POSTed to the webhook for the given format. */
export function buildOpsAlertPayload(
  alert: OpsAlert,
  format: OpsAlertFormat,
  now: Date = new Date(),
): Record<string, unknown> {
  if (format === 'slack') return { text: opsAlertText(alert, now) }
  return {
    type: 'message',
    attachments: [
      {
        contentType: 'application/vnd.microsoft.card.adaptive',
        contentUrl: null,
        content: buildAdaptiveCard(alert, now),
      },
    ],
  }
}

/** The runbook's test message — same sink, same format, clearly not an incident. */
export function buildTestAlert(source: string): OpsAlert {
  return {
    source,
    title: 'Verco ops alert channel check — no action needed',
    lines: [
      `This is a test message from ${source}, sent on request to prove the ops alert channel works.`,
      'If you can read this, real alerts will land here too.',
    ],
    links: [{ label: 'Notification log', url: `${ADMIN_ORIGIN}/admin/notifications` }],
    test: true,
  }
}

/** True for a `{ "test_alert": true }` request body (anything else is a normal run). */
export function isTestAlertRequest(body: unknown): boolean {
  return typeof body === 'object' && body !== null && (body as { test_alert?: unknown }).test_alert === true
}

export type OpsAlertSink =
  | { ok: true; webhookUrl: string; format: OpsAlertFormat }
  | { ok: false; reason: 'not_configured' | 'invalid_format'; error: string }

/**
 * Resolve the configured sink, or say why it can't be used. The error names the
 * secret to fix and never echoes the URL. A watchdog calls this on a HEALTHY run
 * too, so a missing sink shows up before the next incident needs it.
 */
export function resolveOpsAlertSink(config: OpsAlertConfig): OpsAlertSink {
  const webhookUrl = config.webhookUrl?.trim()
  if (!webhookUrl) {
    return { ok: false, reason: 'not_configured', error: 'OPS_ALERT_WEBHOOK_URL is not set' }
  }
  const format = parseOpsAlertFormat(config.format)
  if (!format) {
    const got = redactUrls(String(config.format)).slice(0, 40)
    return {
      ok: false,
      reason: 'invalid_format',
      error: `OPS_ALERT_WEBHOOK_FORMAT must be "teams" or "slack" (got "${got}")`,
    }
  }
  return { ok: true, webhookUrl, format }
}

/**
 * POST an alert to the configured sink. Never throws. Every outcome other than a
 * 2xx answer raises a Sentry warning (`<source>: ops alert not sent — …`) with
 * PII-free context, and returns why, so the caller can choose its HTTP status.
 */
export async function sendOpsAlert(
  alert: OpsAlert,
  config: OpsAlertConfig,
  deps: OpsAlertDeps,
): Promise<OpsAlertResult> {
  const kind = alert.test ? 'test alert' : 'ops alert'
  const context = { source: alert.source, test: alert.test === true }

  const fail = (
    reason: 'not_configured' | 'invalid_format' | 'webhook_failed',
    error: string,
    format: OpsAlertFormat | null,
    status: number | null = null,
    responseBody: string | null = null,
  ): OpsAlertResult => {
    deps.captureWarning(`${alert.source}: ${kind} not sent — ${error}`, {
      ...context,
      reason,
      format,
      status,
    })
    return { delivered: false, reason, error, format, status, responseBody }
  }

  const sink = resolveOpsAlertSink(config)
  if (!sink.ok) return fail(sink.reason, sink.error, null)
  const { webhookUrl, format } = sink

  const fetchImpl = deps.fetch ?? fetch
  let res: Response
  try {
    res = await fetchImpl(webhookUrl, {
      method: 'POST',
      // No Authorization header: a Workflows trigger set to "Anyone" rejects
      // one — the signed URL is the credential.
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(buildOpsAlertPayload(alert, format, deps.now ?? new Date())),
      signal: AbortSignal.timeout(OPS_ALERT_TIMEOUT_MS),
    })
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err)
    return fail('webhook_failed', `webhook POST threw: ${redactUrls(message)}`, format)
  }

  const responseBody = redactUrls((await res.text().catch(() => '')).slice(0, MAX_RESPONSE_BODY_LENGTH))
  if (!res.ok) {
    return fail('webhook_failed', `webhook returned HTTP ${res.status}`, format, res.status, responseBody)
  }
  return { delivered: true, format, status: res.status, responseBody }
}

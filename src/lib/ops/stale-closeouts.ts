/**
 * Stale closeouts — pure logic for the daily stale-closeout alert (#575).
 *
 * Background: Cambridge ran 204 dispatched stops and closed out none of them,
 * and nobody noticed for two weeks (#568). Unclosed stops are unbilled,
 * unproven work, and they under-report the contractual on-time KPI, which keys
 * off stop outcomes (ADR 0009). A whole council could stop closing out and the
 * platform stayed silent — this is the watchdog.
 *
 * Two failure modes, reported separately:
 *   1. Dispatched but never closed out — a `collection_stop` still `Pending`
 *      on a past collection date. Keyed off the STOP (the as-dispatched record,
 *      ADR 0009), not the booking: the stop is what the crew was sent to do.
 *   2. Not dispatched — a `Scheduled` booking whose last collection date has
 *      passed with NO open (`Pending`) stop: none was ever created, its only
 *      stop is a Cancelled one from a date move that was never revived (#486),
 *      or one stream was never dispatched. Nothing is left for a crew to close
 *      out, and the status rollup ignores all-Cancelled stops, so the booking
 *      would sit in Scheduled forever without this.
 *
 * Stale = `thresholdDays` (default 3) or more past the collection date: two
 * days of normal closeout lag are not a problem.
 *
 * ## Not re-alerting the same backlog every day, without hiding it
 *
 * The run is stateless (no last-run table). On a daily schedule the stops dated
 * exactly `today − thresholdDays` are precisely the ones that went stale since
 * yesterday, so:
 *   - a day with newly stale work alerts once, naming each area, and restates
 *     the whole standing backlog underneath;
 *   - a day with only the old backlog stays quiet (a daily wall of the same
 *     numbers gets muted within a week), EXCEPT on Monday, when the backlog is
 *     restated on its own — so a council that went dark once and then had no
 *     more collections can't drop out of sight.
 * A missed run never names that day's cohort individually; it still shows in
 * the backlog totals and the next Monday reminder.
 *
 * PII: the alert carries area codes, counts, dates and admin links only —
 * never booking refs, ids or addresses.
 *
 * Mirror: this `_shared/` file is the source of truth. Its Node twin at
 * `src/lib/ops/stale-closeouts.ts` is generated by `scripts/sync-mirrors.sh`
 * for Vitest (`src/__tests__/ops/stale-closeouts.test.ts`). Pure — no imports,
 * no Deno globals; the EF does the queries and passes rows in.
 */

export type StopStatus = 'Pending' | 'Completed' | 'Non-conformance' | 'Nothing Presented' | 'Cancelled'

export const DEFAULT_STALE_THRESHOLD_DAYS = 3

/** Terminal crew outcomes. Cancelled is neither open nor closed out. */
const CLOSED_OUT: ReadonlySet<StopStatus> = new Set(['Completed', 'Non-conformance', 'Nothing Presented'])

/** One `collection_stop`, flattened with its collection date + area. */
export interface StopRow {
  areaId: string
  areaCode: string
  /** The stop's own collection date (YYYY-MM-DD) — the dispatched date. */
  date: string
  status: StopStatus
  bookingId: string
}

/** One `Scheduled` booking: its area, every item's collection date, and its stops' statuses. */
export interface LiveBookingRow {
  areaCode: string
  dates: string[]
  stopStatuses: StopStatus[]
}

export interface CohortArea {
  areaCode: string
  /** Stops sent out for the cohort date (Cancelled excluded). */
  dispatched: number
  closedOut: number
  open: number
}

export interface BacklogArea {
  areaId: string
  areaCode: string
  openStops: number
  bookings: number
  oldestDate: string
  newestDate: string
}

export interface NotDispatched {
  areaCode: string
  /** The booking's last collection date. */
  date: string
}

export type StaleCloseoutTrigger = 'newly_stale' | 'weekly_backlog'

export interface StaleCloseoutInput {
  /** Today's AWST calendar date (YYYY-MM-DD). */
  today: string
  thresholdDays: number
  /** Every stop dated on the cohort date (any status). */
  cohortStops: StopRow[]
  /** Every `Pending` stop dated on or before the cutoff. */
  openStops: StopRow[]
  /** Every `Scheduled` booking. */
  liveBookings: LiveBookingRow[]
}

export interface StaleCloseoutReport {
  today: string
  thresholdDays: number
  /** today − thresholdDays: the day that went stale since yesterday's run. */
  cohortDate: string
  newlyStale: CohortArea[]
  newlyNotDispatched: NotDispatched[]
  backlog: BacklogArea[]
  notDispatched: NotDispatched[]
  totals: { openStops: number; openBookings: number; notDispatched: number; areas: number }
  trigger: StaleCloseoutTrigger | null
}

export interface StaleCloseoutAlertContent {
  title: string
  lines: string[]
  links: { label: string; url: string }[]
}

export function addDays(date: string, days: number): string {
  const d = new Date(`${date}T00:00:00Z`)
  d.setUTCDate(d.getUTCDate() + days)
  return d.toISOString().slice(0, 10)
}

/** The newest collection date that counts as stale today. */
export function staleCutoffDate(today: string, thresholdDays: number): string {
  return addDays(today, -thresholdDays)
}

/** The backlog is restated on Mondays even when nothing is newly stale. */
export function isBacklogReminderDay(today: string): boolean {
  return new Date(`${today}T00:00:00Z`).getUTCDay() === 1
}

const byCode = (a: { areaCode: string }, b: { areaCode: string }) => a.areaCode.localeCompare(b.areaCode)

/** Per area, the cohort date's dispatched / closed-out / open counts — areas with open stops only. */
export function summariseCohort(stops: StopRow[], cohortDate: string): CohortArea[] {
  const areas = new Map<string, CohortArea>()
  for (const s of stops) {
    if (s.date !== cohortDate || s.status === 'Cancelled') continue
    const area = areas.get(s.areaCode) ?? { areaCode: s.areaCode, dispatched: 0, closedOut: 0, open: 0 }
    area.dispatched += 1
    if (CLOSED_OUT.has(s.status)) area.closedOut += 1
    else area.open += 1
    areas.set(s.areaCode, area)
  }
  return [...areas.values()].filter((a) => a.open > 0).sort((a, b) => b.open - a.open || byCode(a, b))
}

/** Pending stops on or before the cutoff, grouped by area. */
export function summariseBacklog(stops: StopRow[], cutoff: string): BacklogArea[] {
  const areas = new Map<string, BacklogArea & { bookingIds: Set<string> }>()
  for (const s of stops) {
    if (s.status !== 'Pending' || s.date > cutoff) continue
    const area = areas.get(s.areaId) ?? {
      areaId: s.areaId,
      areaCode: s.areaCode,
      openStops: 0,
      bookings: 0,
      oldestDate: s.date,
      newestDate: s.date,
      bookingIds: new Set<string>(),
    }
    area.openStops += 1
    area.bookingIds.add(s.bookingId)
    if (s.date < area.oldestDate) area.oldestDate = s.date
    if (s.date > area.newestDate) area.newestDate = s.date
    areas.set(s.areaId, area)
  }
  return [...areas.values()]
    .map(({ bookingIds, ...area }) => ({ ...area, bookings: bookingIds.size }))
    .sort((a, b) => b.openStops - a.openStops || byCode(a, b))
}

/** `Scheduled` bookings with no open stop whose last collection date is on or before the cutoff. */
export function findNotDispatched(bookings: LiveBookingRow[], cutoff: string): NotDispatched[] {
  const out: NotDispatched[] = []
  for (const b of bookings) {
    if (b.stopStatuses.includes('Pending') || b.dates.length === 0) continue
    const last = b.dates.reduce((max, d) => (d > max ? d : max))
    if (last <= cutoff) out.push({ areaCode: b.areaCode, date: last })
  }
  return out.sort((a, b) => a.date.localeCompare(b.date) || byCode(a, b))
}

export function evaluateStaleCloseouts(input: StaleCloseoutInput): StaleCloseoutReport {
  const cohortDate = staleCutoffDate(input.today, input.thresholdDays)
  const newlyStale = summariseCohort(input.cohortStops, cohortDate)
  const backlog = summariseBacklog(input.openStops, cohortDate)
  const notDispatched = findNotDispatched(input.liveBookings, cohortDate)
  const newlyNotDispatched = notDispatched.filter((n) => n.date === cohortDate)

  const areaCodes = new Set([...backlog.map((a) => a.areaCode), ...notDispatched.map((n) => n.areaCode)])
  const totals = {
    openStops: backlog.reduce((sum, a) => sum + a.openStops, 0),
    openBookings: backlog.reduce((sum, a) => sum + a.bookings, 0),
    notDispatched: notDispatched.length,
    areas: areaCodes.size,
  }

  let trigger: StaleCloseoutTrigger | null = null
  if (newlyStale.length > 0 || newlyNotDispatched.length > 0) trigger = 'newly_stale'
  else if (areaCodes.size > 0 && isBacklogReminderDay(input.today)) trigger = 'weekly_backlog'

  return {
    today: input.today,
    thresholdDays: input.thresholdDays,
    cohortDate,
    newlyStale,
    newlyNotDispatched,
    backlog,
    notDispatched,
    totals,
    trigger,
  }
}

/** "17/10/2026". */
export function formatDate(date: string): string {
  const [y, m, d] = date.split('-')
  return `${d}/${m}/${y}`
}

const WEEKDAYS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']

/** "Fri 17/10/2026". */
function formatDay(date: string): string {
  return `${WEEKDAYS[new Date(`${date}T00:00:00Z`).getUTCDay()]} ${formatDate(date)}`
}

/** Admin bookings list filtered to `Scheduled` bookings with a collection date in range. */
export function worklistUrl(adminOrigin: string, range: { dateFrom?: string; dateTo: string }): string {
  const params = new URLSearchParams({ status: 'Scheduled' })
  if (range.dateFrom) params.set('date_from', range.dateFrom)
  params.set('date_to', range.dateTo)
  return `${adminOrigin}/admin/bookings?${params.toString()}`
}

const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`

/** "VIC 1 booking, KWN-1 2 bookings" — not-dispatched counts per area. */
function notDispatchedByArea(rows: NotDispatched[]): string {
  const counts = new Map<string, number>()
  for (const r of rows) counts.set(r.areaCode, (counts.get(r.areaCode) ?? 0) + 1)
  return [...counts.entries()].map(([code, n]) => `${code} ${plural(n, 'booking')}`).join(', ')
}

function backlogLines(report: StaleCloseoutReport, closedOutSince: Record<string, number>): string[] {
  const { totals } = report
  const lines = [
    `Standing backlog: ${plural(totals.openStops, 'open stop')} on ${plural(totals.openBookings, 'booking')} across ${plural(totals.areas, 'area')}`,
  ]
  for (const a of report.backlog) {
    const range = a.oldestDate === a.newestDate
      ? formatDate(a.oldestDate)
      : `${formatDate(a.oldestDate)}–${formatDate(a.newestDate)}`
    const closed = closedOutSince[a.areaId]
    const closedText = closed === undefined
      ? 'closed-out count unknown'
      : `${closed} closed out since ${formatDate(a.oldestDate)}`
    lines.push(`• ${a.areaCode}: ${plural(a.openStops, 'open stop')}, ${range} · ${closedText}`)
  }
  if (report.notDispatched.length > 0) {
    const oldest = report.notDispatched[0]!.date
    lines.push(`Not dispatched (no open stop): ${notDispatchedByArea(report.notDispatched)} (oldest ${formatDate(oldest)})`)
  }
  return lines
}

/**
 * The alert for a report, or null when nothing warrants one. `closedOutSince`
 * maps a backlog area id → stops closed out in that area from its oldest open
 * stop's date up to the cutoff (the EF counts these only when alerting).
 */
export function buildStaleCloseoutAlert(
  report: StaleCloseoutReport,
  opts: { adminOrigin: string; closedOutSince: Record<string, number> },
): StaleCloseoutAlertContent | null {
  if (report.trigger === null) return null
  const fullBacklog = { label: 'Full backlog', url: worklistUrl(opts.adminOrigin, { dateTo: report.cohortDate }) }
  const switchHint = 'Admin lists one client at a time — switch client to see each council.'

  if (report.trigger === 'weekly_backlog') {
    return {
      title: '⚠️ Stale closeouts — weekly backlog reminder',
      lines: [
        `Nothing newly stale today. Restating everything ${report.thresholdDays}+ days past collection and still not closed out (sent Mondays while any remains).`,
        '',
        ...backlogLines(report, opts.closedOutSince),
        '',
        switchHint,
      ],
      links: [fullBacklog],
    }
  }

  const day = formatDay(report.cohortDate)
  const lines = [`Newly stale — collection day ${day}, ${report.thresholdDays} days ago:`]
  for (const a of report.newlyStale) {
    lines.push(`• ${a.areaCode}: ${a.open} of ${plural(a.dispatched, 'stop')} still open, ${a.closedOut} closed out`)
  }
  if (report.newlyNotDispatched.length > 0) {
    lines.push(`Not dispatched (Scheduled, no open stop): ${notDispatchedByArea(report.newlyNotDispatched)}`)
  }
  lines.push('', ...backlogLines(report, opts.closedOutSince), '', switchHint)

  return {
    title: `⚠️ Stale closeouts — ${day} not closed out ${report.thresholdDays} days on`,
    lines,
    links: [
      { label: `Worklist — ${day}`, url: worklistUrl(opts.adminOrigin, { dateFrom: report.cohortDate, dateTo: report.cohortDate }) },
      fullBacklog,
    ],
  }
}
